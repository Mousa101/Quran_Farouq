export const EMAIL_DOMAIN = '@faroq.com';
export const emailLocalPart = (email) => (email || '').split('@')[0];
export const buildEmail = (localPart) => {
  const local = (localPart || '').trim().split('@')[0];
  return local ? local + EMAIL_DOMAIN : '';
};

